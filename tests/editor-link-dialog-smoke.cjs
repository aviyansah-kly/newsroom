const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded',timeout:45000});
  await page.waitForSelector('#nrLinkOverlay',{state:'attached',timeout:15000});
  await page.waitForFunction(()=>!!window.sixdeskTiptap,{timeout:35000});
  const open=async()=>{await page.evaluate(()=>document.querySelector('#linkTool')?.dispatchEvent(new MouseEvent('click',{bubbles:true,cancelable:true})));await page.locator('#nrLinkOverlay').waitFor({state:'visible'})};
  await open();
  const textBox=await page.locator('#nrLinkText').boundingBox();
  const searchBox=await page.locator('#nrLinkSearch').boundingBox();
  if(!textBox||!searchBox||textBox.y>=searchBox.y)throw Error('Text field must be above search');
  if(await page.locator('#nrLinkResults [data-article-id]').count()!==3)throw Error('Default preview must display only 3 articles');
  if(await page.locator('#nrLinkDemoBadge').count())throw Error('Demo badge should not appear');
  const list=page.locator('#nrLinkResults');
  const listBox=await list.boundingBox();
  const selectedCard=page.locator('#nrLinkResults [data-article-id]').first();
  await selectedCard.click();
  const cardBox=await selectedCard.boundingBox();
  if(cardBox.x<listBox.x||cardBox.x+cardBox.width>listBox.x+listBox.width)throw Error('Selected article border exceeds list bounds');
  if(await page.locator('#nrLinkTabInternal').getAttribute('aria-selected')!=='true')throw Error('Original Internal Link tab must open first');
  if(await page.locator('#linkPopup.open').count())throw Error('Legacy popup visible');
  await page.locator('#nrLinkSearch').fill('minyak');
  if(!await page.locator('#nrLinkResults [data-article-id]').count())throw Error('Original internal search should show matching articles');
  await page.locator('#nrLinkResults [data-article-id]').first().click();
  await page.locator('#nrLinkText').fill('Harga minyak');
  if(!await page.locator('#nrLinkApply').isEnabled())throw Error('Selecting an internal article should enable insert');
  await page.locator('#nrLinkApply').click();
  await page.locator('#nrLinkOverlay').waitFor({state:'hidden'});
  const editor=page.locator('#tiptap-editor .tiptap-editor');
  if(!await editor.locator('a[href*="demo-"]').count())throw Error('Internal link not inserted');
  await open();
  await page.locator('#nrLinkAi').click();
  await page.waitForFunction(()=>document.getElementById('nrLinkAi')?.getAttribute('aria-busy')==='false');
  if(await page.locator('#nrLinkResults [data-article-id]').count()!==3)throw Error('Expected three dummy AI suggestions');
  await page.locator('#nrLinkTabExternal').click();
  await page.locator('#nrLinkExternalUrl').fill('https://example.com/news');
  await page.locator('#nrLinkText').fill('Sumber berita');
  await page.locator('#nrLinkNofollow').check();
  await page.locator('#nrLinkApply').click();
  const a=await editor.locator('a[href="https://example.com/news"]').first().evaluate(e=>({rel:e.rel,target:e.target,text:e.textContent}));
  if(a.target!=='_blank'||!a.rel.includes('nofollow')||a.text!=='Sumber berita')throw Error('External link attributes incorrect');
  await open();await page.locator('#nrLinkClose').click();
  if(await page.locator('#nrLinkOverlay').isVisible())throw Error('Close failed');
  if(errors.length)throw Error('Browser errors: '+errors.join('; '));
  console.log('PASS: previous Internal/External/AI flow remains available');
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
