const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1480,height:940}});
 const errs=[];page.on('pageerror',e=>errs.push(e.stack||e.message));
 page.on('dialog',async d=>{await d.dismiss();throw Error('Unexpected native browser dialog: '+d.type())});
 await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded',timeout:45000});
 await page.waitForSelector('#nrLinkOverlay',{state:'attached',timeout:15000});
 await page.waitForFunction(()=>!!window.sixdeskTiptap,{timeout:35000});
 const editor=page.locator('#tiptap-editor .tiptap-editor');
 await page.locator('[data-classic-command="link"]').first().click();
 await page.locator('#nrLinkOverlay').waitFor({state:'visible'});
 if(await page.locator('#nrLinkTabInternal').getAttribute('aria-selected')!=='true')throw Error('Internal tab should open by default');
 if(await page.locator('#linkPopup.open').count())throw Error('Old popup also opened');
 await page.locator('#nrLinkAi').click();
 if(await page.locator('#nrLinkAi').getAttribute('aria-busy')!=='true')throw Error('AI suggestion button should expose loading state');
 await page.waitForFunction(()=>document.getElementById('nrLinkAi')?.getAttribute('aria-busy')==='false');
 if(await page.locator('.nr-link-demo-badge').innerText()!=='AI DEMO')throw Error('Missing AI demo disclosure');
 if(await page.locator('#nrLinkResults [data-article-id]').count()!==3)throw Error('Expected 3 dummy AI suggestions');
 if(await page.locator('.nr-link-result-reason').count()!==3)throw Error('AI suggestions should explain contextual relevance');
 await page.locator('#nrLinkResults [data-article-id]').first().click();
 const suggested=await page.locator('#nrLinkText').inputValue();
 if(!suggested)throw Error('Suggestion did not fill display text');
 await page.locator('#nrLinkApply').click();
 await page.locator('#nrLinkOverlay').waitFor({state:'hidden'});
 const created=await editor.locator('a[href*="demo-"]').first().evaluate(e=>({href:e.href,text:e.textContent}));
 if(!created.text||!created.href.includes('liputan6.com'))throw Error('Internal link not inserted into editor');
 console.log('INTERNAL',JSON.stringify(created));
 await editor.click();
 await page.locator('[data-classic-command="link"]').first().click();
 await page.locator('#nrLinkTabExternal').click();
 if(!(await page.locator('#nrLinkNewTab').isChecked()))throw Error('External link should default to opening in a new tab');
 if(await page.locator('#nrLinkNofollow').isChecked())throw Error('External link should not default to nofollow');
 await page.locator('#nrLinkExternalUrl').fill('https://example.com/news');
 await page.locator('#nrLinkText').fill('Sumber berita');
 await page.locator('#nrLinkNewTab').check();
 await page.locator('#nrLinkNofollow').check();
 await page.locator('#nrLinkApply').click();
 const external=await editor.locator('a[href="https://example.com/news"]').first().evaluate(e=>({href:e.href,rel:e.rel,target:e.target,text:e.textContent}));
 if(external.target!=='_blank'||!external.rel.includes('nofollow')||external.text!=='Sumber berita')throw Error('External link attributes incorrect: '+JSON.stringify(external));
 console.log('EXTERNAL',JSON.stringify(external));
 await page.locator('[data-classic-command="link"]').first().click();
 await page.locator('#nrLinkClose').click();
 if(await page.locator('#nrLinkOverlay').isVisible())throw Error('Dialog did not close');
 const modalCount=await page.locator('#nrLinkOverlay').count();if(modalCount!==1)throw Error('Duplicate dialog');
 console.log('PASS: shared link modal, AI dummy suggestions, apply internal/external with attributes, close');
 console.log('PAGE ERRORS',JSON.stringify(errs.slice(0,6)));
 await browser.close();
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
